def get_eeqbc_rvdw(
    device: torch.device | None = None,
    dtype: torch.dtype | None = None,
) -> Tensor:
    """
    Pairwise van-der-Waals radii matrix `(104, 104)` for EEQ_BC in Angstrom
    (matching ``get_vdw_rad(jzp, izp) * autoaa * 0.5 * (rvdw_scale(isp) + rvdw_scale(jsp))``
    in ``multicharge_param::new_eeqbc2025_model``).
    """
    vdw_bohr = VDW_PAIRWISE(device=device, dtype=torch.float64)
    scale = rvdw_scale.to(device=device, dtype=torch.float64)
    pair_scale = 0.5 * (scale[:, None] + scale[None, :])
    pair_scale[0, :] = 0.0
    pair_scale[:, 0] = 0.0
    rvdw = vdw_bohr * AU2AA * pair_scale
    if dtype is not None:
        rvdw = rvdw.to(dtype=dtype)
    return rvdw
